self.addEventListener('install', function(e) {
    // Baixa os arquivos aos poucos e ignora os que falharem (servidor local de celular engasga com muitos pedidos juntos)
    e.waitUntil(caches.open(CACHE).then(function(c) {
        var i = 0;
        function batch() {
            if (i >= FILES.length) { return; }
            var part = FILES.slice(i, i + 6); i += 6;
            return Promise.all(part.map(function(u) { return c.add(u).catch(function() {}); })).then(batch);
        }
        return batch();
    }));
    self.skipWaiting();
});

self.addEventListener('activate', function(e) {
    e.waitUntil(caches.keys().then(function(keys) {
        return Promise.all(keys.filter(function(k) { return k.indexOf('frogger-') === 0 && k !== CACHE; })
                               .map(function(k) { return caches.delete(k); }));
    }));
    self.clients.claim();
});

// Network first (so edits show up right away), cache as the offline fallback
self.addEventListener('fetch', function(e) {
    if (e.request.method !== 'GET') { return; }
    e.respondWith(fetch(e.request, { cache: 'no-cache' }).then(function(res) {   // no-cache = pergunta ao servidor se mudou (ignora o cache do navegador)
        if (res.ok && new URL(e.request.url).origin === self.location.origin) {
            var copy = res.clone();
            caches.open(CACHE).then(function(c) { c.put(e.request, copy); });
        }
        return res;
    }).catch(function() { return caches.match(e.request); }));
});
